test('organiser dashboard keeps event counts, gate entries and exhibitor chart in sync',()=>{
  s.resetDemo();
  const expo=s.getExpos()[0],visitor=s.getVisitors({expoId:expo.id}).find(v=>v.status!=='Cancelled'&&v.checkedIn);
  const account={id:'dashboard-exhibitor',company:'Actual Company',name:'Owner',expoId:expo.id,booth:''};
  s.getExhibitors().push(account);
  s.db().stallCheckins=[{id:'visit',visitorId:visitor.id,exhibitorId:account.id,expoId:expo.id,status:'Success'},{id:'repeat',visitorId:visitor.id,exhibitorId:account.id,expoId:expo.id,status:'Success'}];
  let data=s.getOrganiserDashboardData(expo.id);
  assert.equal(data.exhibitors.length,1);
  assert.equal(data.stallRows.length,1);
  assert.equal(data.stallRows[0].checkins,1);
  assert.equal(data.arrived,data.entries.length);
  const original=data.arrived;
  s.db().checkins.push({...data.entries[0],id:'duplicate-entry'});
  data=s.getOrganiserDashboardData(expo.id);
  assert.equal(data.arrived,original);
  assert.equal(data.active.length-data.arrived,data.active.filter(v=>!v.checkedIn).length);
  assert.equal(s.getOrganiserDashboardData(s.getExpos()[1].id).exhibitors.length,0);
  s.db().stallCheckins=[];
  assert.equal(s.getOrganiserDashboardData(expo.id).stallRows[0].checkins,0);
});

test('exhibitor scans classify own leads, move columns and record one stall visit',async()=>{
  s.resetDemo();
  const expo=s.getExpos()[0];
  const details={company:'Lead Company',name:'Lead Owner',email:'leads@test.com',phone:'+919555555555',expoId:expo.id,password:'lead-password'};
  const account=await s.createExhibitorAccount(details);
  const visitor=s.getVisitors({expoId:expo.id}).find(v=>v.type==='Visitor'&&v.status!=='Cancelled');
  const gateCount=s.getCheckInHistory().length;
  assert.equal(s.verifyExhibitorLeadQR(`EXPO:${visitor.token}`).id,visitor.id);
  assert.equal(s.getExhibitorLeads().length,0);
  const lead=s.saveExhibitorLead(visitor.token,'Hot');
  assert.equal(s.getExhibitorLeads()[0].temperature,'Hot');
  s.saveExhibitorLead(visitor.token,'Cold');
  assert.equal(s.getExhibitorLeads().length,1);
  assert.equal(s.getExhibitorLeads()[0].id,lead.id);
  assert.equal(s.getExhibitorLeads()[0].temperature,'Cold');
  assert.equal(s.getOrganiserDashboardData(expo.id).stallRows[0].checkins,1);
  assert.equal(s.getCheckInHistory().length,gateCount);
  assert.equal(JSON.parse(store.get('expoflow-v1')).exhibitorLeads.length,1);
  assert.throws(()=>s.saveExhibitorLead('invalid','Hot'),/Invalid QR/);
  assert.throws(()=>s.saveExhibitorLead(visitor.token,'Other'),/Choose Hot/);
  const cancelled=s.getVisitors().find(v=>v.expoId===expo.id&&v.status==='Cancelled');
  assert.throws(()=>s.saveExhibitorLead(cancelled.token,'Hot'),/Cancelled Registration/);
  const wrong=s.getVisitors().find(v=>v.expoId!==expo.id);
  assert.throws(()=>s.saveExhibitorLead(wrong.token,'Hot'),/Wrong Expo/);
  const other=await s.createExhibitorAccount({...details,email:'other-leads@test.com',phone:'+919666666666'});
  assert.equal(s.getExhibitorLeads().length,0);
  s.saveExhibitorLead(visitor.token,'Hot');
  assert.equal(s.getExhibitorLeads()[0].exhibitorId,other.id);
  await s.loginExhibitor(details.email,details.password);
  assert.equal(s.getExhibitorLeads()[0].exhibitorId,account.id);
  assert.equal(s.getExhibitorLeads()[0].temperature,'Cold');
  const replacedToken=visitor.token;
  s.regenerateQRToken(visitor.id);
  assert.throws(()=>s.saveExhibitorLead(replacedToken,'Hot'),/Invalid QR/);
  s.logoutExhibitor();
  assert.throws(()=>s.getExhibitorLeads(),/log in/);
  assert.throws(()=>s.saveExhibitorLead(visitor.token,'Hot'),/log in/);
});

